// Generates the island positions once, during development. Run with: npm run layout
// The browser app only reads the saved result and never loads graphology.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { UndirectedGraph } from 'graphology';
import circular from 'graphology-layout/circular.js';
import forceAtlas2 from 'graphology-layout-forceatlas2';
import { BRIDGES, ISLANDS } from '../src/archipelago/topology.js';
import { compareIds } from '../src/engine/ids.js';

const ITERATIONS = 500;
const SETTINGS = { linLogMode: true };
const MARGIN = 10;
const TARGET_RANGE = 100 - 2 * MARGIN;
const OUTPUT = fileURLToPath(new URL('../src/archipelago/positions.js', import.meta.url));

const byId = (a, b) => compareIds(a.id, b.id);
const round = (value) => Math.round(value * 100) / 100;

export function computeLayout(nodes, edges) {
  const graph = new UndirectedGraph();
  // Force layouts depend on insertion order, so sort before adding anything.
  for (const node of [...nodes].sort(byId)) graph.addNode(node.id);
  for (const edge of [...edges].sort(byId)) graph.addEdgeWithKey(edge.id, edge.a, edge.b);
  circular.assign(graph);
  const raw = forceAtlas2(graph, { iterations: ITERATIONS, settings: SETTINGS });
  return rescale(orient(raw, graph.nodes()[0]));
}

// The map panel is wider than tall, so the map should be too, reading from its first island.
export function orient(positions, firstId) {
  const entries = Object.entries(positions);
  const extent = (axis) => {
    const values = entries.map(([, point]) => point[axis]);
    return { min: Math.min(...values), max: Math.max(...values) };
  };
  const { x, y } = { x: extent('x'), y: extent('y') };
  const swap = y.max - y.min > x.max - x.min;
  const horizontal = swap ? y : x;
  const firstX = swap ? positions[firstId].y : positions[firstId].x;
  const mirror = firstX > (horizontal.min + horizontal.max) / 2;

  const oriented = {};
  for (const [id, point] of entries) {
    const newX = swap ? point.y : point.x;
    oriented[id] = { x: mirror ? -newX : newX, y: swap ? point.x : point.y };
  }
  return oriented;
}

// ForceAtlas2 coordinates can be any size, but the brief requires 0 to 100.
export function rescale(positions) {
  const points = Object.values(positions);
  const minX = Math.min(...points.map((p) => p.x));
  const minY = Math.min(...points.map((p) => p.y));
  const rangeX = Math.max(...points.map((p) => p.x)) - minX;
  const rangeY = Math.max(...points.map((p) => p.y)) - minY;
  const largestRange = Math.max(rangeX, rangeY);

  const scaled = {};
  for (const [id, point] of Object.entries(positions)) {
    scaled[id] =
      largestRange === 0
        ? { x: 50, y: 50 }
        : {
            x: round((point.x - minX) * (TARGET_RANGE / largestRange) + MARGIN),
            y: round((point.y - minY) * (TARGET_RANGE / largestRange) + MARGIN),
          };
  }
  return scaled;
}

export function formatPositions(positions) {
  const lines = Object.keys(positions)
    .sort(compareIds)
    .map((id) => `  ${id}: { x: ${positions[id].x}, y: ${positions[id].y} },`);
  return `// Generated by scripts/layout.js. Run "npm run layout" instead of editing by hand.\nexport const POSITIONS = {\n${lines.join('\n')}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, formatPositions(computeLayout(ISLANDS, BRIDGES)));
  console.log(`Wrote ${OUTPUT}`);
}
